/* Server boshqa mintaqada (Netlify: UTC) boʻlsa ham sana va vaqt toʻgarak vaqti boʻyicha. */
const fmt = new Intl.DateTimeFormat('en-GB', { timeZone: ZONE, year: 'numeric', month: '2-digit', day: '2-digit', hour: '2-digit', minute: '2-digit', hourCycle: 'h23' });
export function local(d = new Date()) {
  const p = Object.fromEntries(fmt.formatToParts(d).map((x) => [x.type, x.value]));
  const date = `${p.year}-${p.month}-${p.day}`;
  return { date, time: `${p.hour}:${p.minute}`, dow: new Date(date + 'T00:00:00Z').getUTCDay() || 7 };
}
export const today = (d) => local(d).date;
export function daysAgo(n) { const d = new Date(today() + 'T00:00:00Z'); d.setUTCDate(d.getUTCDate() - n); return d.toISOString().slice(0, 10); }
export const lastMonths = (k) => Array.from({ length: k }, (_, i) => { const d = new Date(today().slice(0, 7) + '-01T00:00:00Z'); d.setUTCMonth(d.getUTCMonth() - (k - 1 - i)); return d.toISOString().slice(0, 7); });

