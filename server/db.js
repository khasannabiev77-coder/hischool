/* Katta sonlar (vaqt, COUNT) va kasrlar (AVG) JavaScript soni boʻlib qaytadi. */
const PARSE = { 20: Number, 1700: Number };
const current = new AsyncLocalStorage(); // ochiq tranzaksiya ulanishi
let engine, starting;

/** PGlite fayllarini ikki jarayon birga ochsa baza buziladi, shuning uchun qulf. */
function lock() {
  const file = path.join(DATA, 'pg.lock');
  for (let i = 0; i < 2; i++) {
    try { writeFileSync(file, String(process.pid), { flag: 'wx' }); process.on('exit', () => rmSync(file, { force: true })); return; } catch (e) {
      if (e.code !== 'EEXIST') throw e;
      const pid = Number(readFileSync(file, 'utf8'));
      let alive = false;
      try { if (pid) { process.kill(pid, 0); alive = true; } } catch (x) { alive = x.code === 'EPERM'; }
      if (alive) throw Object.assign(new Error('Dastur allaqachon ochiq. Avval oʻsha oynani yoping.'), { code: 'LOCKED' });
      rmSync(file, { force: true }); // oldingi jarayon majburan yopilgan
    }
  }
}

async function connect() {
  const url = process.env.DATABASE_URL || process.env.NETLIFY_DB_URL || process.env.POSTGRES_URL;
  if (url) {
    for (const [oid, f] of Object.entries(PARSE)) pg.types.setTypeParser(Number(oid), f);
    const pool = new pg.Pool({ connectionString: url, max: Number(process.env.HS_DB_POOL || 4), idleTimeoutMillis: 8000, connectionTimeoutMillis: 10000, allowExitOnIdle: true });
    pool.on('error', (e) => console.error('db:', e.message)); // uxlab qolgan baza ulanishni uzishi mumkin
    return {
      query: async (sql, a) => (await (current.getStore() || pool).query(sql, a)).rows,
      script: async (sql) => {
        const c = await pool.connect();
        try { await c.query('BEGIN'); await c.query('SELECT pg_advisory_xact_lock(727001)'); await c.query(sql); await c.query('COMMIT'); }
        catch (e) { await c.query('ROLLBACK').catch(() => {}); throw e; } finally { c.release(); }
      },
      close: () => pool.end(),
      tx: async (fn) => {
        const c = await pool.connect();
        try { await c.query('BEGIN'); const r = await current.run(c, fn); await c.query('COMMIT'); return r; }
        catch (e) { await c.query('ROLLBACK').catch(() => {}); throw e; } finally { c.release(); }
      },
    };
  }
  if (SERVERLESS) throw new Error('Baza ulanmagan: DATABASE_URL yoʻq.');
  mkdirSync(DATA, { recursive: true });
  lock();
  const lib = '@electric-sql/' + (process.env.HS_PG || 'pglite'); // Netlify toʻplamiga tushmasin
  const { PGlite } = await import(lib);
  const db = await PGlite.create({ dataDir: path.join(DATA, 'pg'), parsers: PARSE });
  return {
    query: async (sql, a) => (await (current.getStore() || db).query(sql, a)).rows,
    script: (sql) => db.exec(sql),
    tx: (fn) => db.transaction((t) => current.run(t, fn)),
    close: () => db.close(),
  };
}

async function start() {
  const e = await connect();
  try { await migrate(e); } catch (x) { await e.close?.().catch(() => {}); throw x; } // ochiq ulanish qolib ketmasin
  engine = e;
}
async function migrate(e) {
  const v = await e.query(`SELECT v FROM settings WHERE k = 'schema'`, []).catch((x) => { if (x.code === '42P01') return []; throw x; });
  const now = Number(v[0]?.v || 0);
  if (now < SCHEMA_VERSION) {
    const steps = Object.keys(UPGRADES).filter((k) => Number(k) > now).map((k) => UPGRADES[k]).join('\n');
    await e.script(`${SCHEMA} ${steps} INSERT INTO settings VALUES ('schema', '${SCHEMA_VERSION}') ON CONFLICT (k) DO UPDATE SET v = excluded.v;`);
  }
}
const ready = () => (engine ? null : (starting ??= start().catch((e) => { starting = null; throw e; })));
export const close = async () => { await engine?.close?.(); };

/* `?` va `?1` belgilarini Postgres `$1` ga oʻtkazadi. */
const cache = new Map();
function convert(sql) {
  let s = cache.get(sql);
  if (!s) { let n = 0; s = sql.replace(/\?(\d+)?/g, (_, d) => '$' + (d || ++n)); cache.set(sql, s); }
  return s;
}
export async function all(sql, ...a) { await ready(); return engine.query(convert(sql), a); }
export async function get(sql, ...a) { return (await all(sql, ...a))[0]; }
export const run = all;
export async function insert(sql, ...a) { return (await get(`${sql} RETURNING id`, ...a)).id; }
export async function tx(fn) { await ready(); return current.getStore() ? fn() : engine.tx(fn); }

